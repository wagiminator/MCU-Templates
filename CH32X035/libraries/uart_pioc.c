// Init PIOC as UART transmitter with default BAUD rate
void PUART_init(void) {
  PIOC_init(PUART_IO);                      // init PIOC, TX pin to PIOC
  PIOC_load(PUART_PIOC_CODE, sizeof(PUART_PIOC_CODE)); // load program
  PIOC_start();                             // start program
  PUART_setBAUD(PUART_BAUD);                // set default BAUD rate
  PIOC_write(PUART_PIN);                    // configuration byte: TX pin
}

// Send character via UART
void PUART_write(const char c) {
  PIOC_write(c);                            // waits until PIOC has read last byte
}

// Send buffer (*buf) with length (len) via UART
void PUART_writeBuffer(const uint8_t* buf, uint16_t len) {
  while(len--) PUART_write(*buf++);
}
